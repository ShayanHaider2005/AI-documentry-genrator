async def run_browser_execution_demo(goal: str, headless: bool = True):
    """Run a complete browser execution demo from natural language goal.

    Args:
        goal: Natural language testing goal
        headless: Whether to run browser headless
    """
    # Step 1: Generate the plan
    from planner import generate_plan
    plan = generate_plan(goal)

    if not plan:
        print("❌ Could not parse goal.")
        return

    print("=" * 70)
    print("BROWSERPILOT: Browser Execution Engine")
    print("=" * 70)
    print(f"\n1. Generating test plan from goal: '{goal}'")
    print(f"   Steps: {len(plan['steps'])}")

    # Step 2: Execute the plan in browser
    print(f"\n2. Executing test plan in browser (headless={headless})...")
    report = await execute_plan(plan, headless=headless)

    # Step 3: Display results
    print(f"\n3. EXECUTION RESULTS:")
    print(f"   Total steps: {report['summary']['total_steps']}")
    print(f"   Passed: {report['summary']['passed']}")
    print(f"   Failed: {report['summary']['failed']}")
    print(f"   Errors: {report['summary']['errors']}")
    print(f"   Timeouts: {report['summary']['timeouts']}")
    print(f"   Success rate: {report['summary']['success_rate']}%")
    print(f"   Bugs detected: {report['bugs_detected']}")
    print(f"   Execution time: {report['execution_time']}s")

    print(f"\n4. STEP DETAILS:")
    for step_result in report["steps"]:
        status_symbol = "✓" if step_result["status"] == "pass" else "✗" if step_result["status"] == "fail" else "✕" if step_result["status"] == "error" else "⏱"
        print(f"   {step_result['step']}. {status_symbol} {step_result['action']}", end="")
        if step_result["evidence"]:
            print(f" - {step_result['evidence'][:60]}", end="")
        if step_result.get("error"):
            print(f" [ERROR: {step_result['error'][:40]}]", end="")
        print()

    print(f"\n5. EVIDENCE:")
    print(f"   Screenshots captured: {len(report['screenshots'])}")
    for ss in report["screenshots"][:3]:  # Show first 3
        print(f"     - {ss}")
    if len(report["screenshots"]) > 3:
        print(f"     ... and {len(report['screenshots']) - 3} more")

    print(f"\n6. BUGS FROM PLANNING PHASE:")
    for bug in report["bugs_detected"]:
        print(f"   - {bug}")

    print("\n" + "=" * 70)
    print("BROWSER EXECUTION COMPLETE")


def main():
    """CLI entry point for browser execution demo."""
    import sys

    if len(sys.argv) < 2:
        print("Usage: python browser_engine.py \"natural language goal\" [headless=True/False]")
        print("\nExamples:")
        print('  python browser_engine.py "Test user can register with valid email"')
        print('  python browser_engine.py "Login with correct credentials" headless=False')
        sys.exit(1)

    goal = " ".join(sys.argv[1:])
    headless = True
    if len(sys.argv) > 2:
        headless = sys.argv[2].lower() not in ("false", "no", "0")

    asyncio.run(run_browser_execution_demo(goal, headless=headless))


if __name__ == "__main__":
    main()