"""BrowserPilot Browser Execution Engine.

Uses Playwright to execute test plans generated by the AI planner.
Controls a real browser, executes actions, captures evidence, and
returns results for the verification engine.

Supported actions:
- navigate: Go to a URL
- input: Enter text into a form field
- click: Click an element
- assert: Verify text or state
- screenshot: Take a screenshot
"""

from __future__ import annotations

import asyncio
import json
import time
import base64
from typing import Any, Dict, List, Optional, Tuple

from playwright.async_api import async_playwright, TimeoutError as PlaywrightTimeoutError


# ══════════════════════════════════════
# Execution Result
# ══════════════════════════════════════

ExecutionResult = Dict[str, Any]


def make_result(step_num: int, action: str, status: str, evidence: str = "", error: str = "") -> ExecutionResult:
    """Create a standardized execution result dict."""
    return {
        "step": step_num,
        "action": action,
        "status": status,  # "pass", "fail", "error", "timeout"
        "evidence": evidence,
        "error": error,
    }


# ══════════════════════════════════════
# Core: Execute Single Step
# ══════════════════════════════════════

async def execute_step(
    page,
    step: Dict[str, Any],
    timeout: int = 10,
) -> ExecutionResult:
    """Execute a single test step against the current page.

    Args:
        page: Playwright page object
        step: Step dict from the test plan
        timeout: Maximum wait time in seconds

    Returns:
        Execution result dict
    """
    action = step.get("action")
    selector = step.get("selector")
    value = step.get("value")
    expected = step.get("expected")

    result: ExecutionResult = make_result(step_num=0, action=action, status="error")

    try:
        if action == "navigate":
            url = value or "/"
            await page.goto(url, wait_until="domcontentloaded", timeout=timeout * 1000)
            result = make_result(
                step_num=step.get("step", 1),
                action="navigate",
                status="pass",
                evidence=f"Navigated to {url}; page title: {await page.title()}",
            )

        elif action == "input":
            if not selector or value is None:
                return make_result(
                    step_num=step.get("step", 1),
                    action="input",
                    status="error",
                    evidence="Input step missing selector or value",
                    error="Missing selector or value",
                )

            element = await page.wait_for_selector(selector, timeout=timeout * 1000)
            if element:
                await element.fill(value)
                await element.press("Tab")  # Move focus
                result = make_result(
                    step_num=step.get("step", 1),
                    action="input",
                    status="pass",
                    evidence=f"Entered '{value}' into {selector}",
                )
            else:
                return make_result(
                    step_num=step.get("step", 1),
                    action="input",
                    status="fail",
                    evidence=f"Element not found: {selector}",
                    error=f"Selector '{selector}' not found on page",
                )

        elif action == "click":
            if not selector:
                return make_result(
                    step_num=step.get("step", 1),
                    action="click",
                    status="error",
                    evidence="Click step missing selector",
                    error="Missing selector",
                )

            element = await page.wait_for_selector(selector, timeout=timeout * 1000)
            if element:
                await element.click()
                result = make_result(
                    step_num=step.get("step", 1),
                    action="click",
                    status="pass",
                    evidence=f"Clicked element: {selector}",
                )
            else:
                return make_result(
                    step_num=step.get("step", 1),
                    action="click",
                    status="fail",
                    evidence=f"Element not found: {selector}",
                    error=f"Selector '{selector}' not found",
                )

        elif action == "assert":
            if not expected:
                return make_result(
                    step_num=step.get("step", 1),
                    action="assert",
                    status="error",
                    evidence="Assert step missing expected value",
                    error="Missing expected value",
                )

            # Get actual page content for verification
            try:
                body_text = await page.inner_text("body")
                found = expected.lower() in body_text.lower()
            except Exception:
                found = False

            if found:
                result = make_result(
                    step_num=step.get("step", 1),
                    action="assert",
                    status="pass",
                    evidence=f"Verified '{expected}' found on page body",
                )
            else:
                # Try checking specific selector
                if selector:
                    try:
                        elem_text = await page.text_content(selector)
                        found = expected.lower() in (elem_text or "").lower()
                    except Exception:
                        found = False

                    if found:
                        result = make_result(
                            step_num=step.get("step", 1),
                            action="assert",
                            status="pass",
                            evidence=f"Verified '{expected}' via selector: {selector}",
                        )
                    else:
                        result = make_result(
                            step_num=step.get("step", 1),
                            action="assert",
                            status="fail",
                            evidence=f"Could not verify '{expected}' on page",
                            error=f"Expected text '{expected}' not found on page",
                        )
                else:
                    result = make_result(
                        step_num=step.get("step", 1),
                        action="assert",
                        status="fail",
                        evidence=f"Could not verify '{expected}' on page",
                        error=f"Expected text '{expected}' not found on page",
                    )
        elif action == "screenshot":
            filepath = value or f"screenshot_step_{step_num}.png"
            await page.screenshot(path=filepath)
            result = make_result(
                step_num=step.get("step", 1),
                action="screenshot",
                status="pass",
                evidence=f"Screenshot saved to {filepath}",
            )

        else:
            result = make_result(
                step_num=step.get("step", 1),
                action=action,
                status="error",
                evidence=f"Unknown action: {action}",
                error=f"Unsupported action: {action}",
            )

    except PlaywrightTimeoutError:
        result = make_result(
            step_num=step.get("step", 1),
            action=action,
            status="timeout",
            evidence=f"Timeout ({timeout}s) performing {action}",
            error=f"Playwright timeout on action: {action}",
        )
    except Exception as e:
        result = make_result(
            step_num=step.get("step", 1),
            action=action,
            status="error",
            evidence="",
            error=str(e),
        )

    return result


# ══════════════════════════════════════
# Core: Execute Full Plan
# ══════════════════════════════════════

async def execute_plan(
    plan: Dict[str, Any],
    headless: bool = True,
    timeout: int = 30,
) -> Dict[str, Any]:
    """Execute a complete test plan using Playwright.

    Args:
        plan: Test plan dict from the AI planner
        headless: Whether to run browser headless (no UI)
        timeout: Maximum total execution time in seconds

    Returns:
        Execution report dict with results, summary, and evidence
    """
    plan_id = plan.get("plan_id", f"plan_{int(time.time())}")
    steps = plan.get("steps", [])
    goal = plan.get("goal", "")

    report: ExecutionResult = {
        "plan_id": plan_id,
        "goal": goal,
        "steps": [],
        "summary": {
            "total_steps": len(steps),
            "passed": 0,
            "failed": 0,
            "errors": 0,
            "timeouts": 0,
            "success_rate": 0.0,
        },
        "screenshots": [],
        "bugs_detected": plan.get("bugs_detected", []),
        "execution_time": 0.0,
    }

    start_time = time.time()

    async with async_playwright() as p:
        browser = await p.chromium.launch(headless=headless)
        context = await browser.new_context()
        page = await context.new_page()

        try:
            for i, step in enumerate(steps, 1):
                # Mark step number in the step dict
                step_with_num = {**step, "step": i}

                # Execute the step
                result = await execute_step(page, step_with_num, timeout=timeout)

                # Add step to report
                report["steps"].append(result)

                # Update summary
                if result["status"] == "pass":
                    report["summary"]["passed"] += 1
                elif result["status"] == "fail":
                    report["summary"]["failed"] += 1
                elif result["status"] == "error":
                    report["summary"]["errors"] += 1
                elif result["status"] == "timeout":
                    report["summary"]["timeouts"] += 1

                # Capture screenshot after each step (optional)
                try:
                    ss_path = f"reports/ss_{plan_id}_step_{i}.png"
                    await page.screenshot(path=ss_path)
                    report["screenshots"].append(ss_path)
                except Exception:
                    pass  # Screenshot failure doesn't stop execution

        finally:
            await context.close()
            await browser.close()

    # Calculate final summary
    total = report["summary"]["total_steps"]
    passed = report["summary"]["passed"]
    report["summary"]["success_rate"] = round((passed / total) * 100, 1) if total > 0 else 0.0
    report["execution_time"] = round(time.time() - start_time, 2)

    return report


